    <p><strong>Datos personales sensibles.</strong> Sistemas Contino no recaba datos personales sensibles a través del Portal. Le pedimos no incluir en los documentos que cargue información de esa naturaleza que no sea indispensable.</p>
    <p><strong>Datos de terceros.</strong> Si usted proporciona datos de terceros (por ejemplo, de sus proveedores como referencias), declara contar con su autorización para ello y haberles informado sobre el presente aviso.</p>

    <h4 class="ob-legal__h">4. Finalidades del tratamiento.</h4>
    <p class="mb-1"><strong>Finalidades primarias (necesarias para la relación con usted).</strong></p>
    <ul class="ob-legal__list">
        <li>Registrarlo como solicitante en el Portal y crear su expediente de crédito.</li>
        <li>Verificar su identidad y, en su caso, la personalidad y facultades del representante legal.</li>
        <li>Analizar y evaluar su capacidad de pago y solvencia, a fin de resolver sobre el otorgamiento, monto y condiciones de la línea de crédito o financiamiento.</li>
        <li>Verificar las referencias comerciales proporcionadas.</li>
        <li>Elaborar, formalizar y dar cumplimiento a los contratos de arrendamiento, compraventa a plazos o financiamiento que, en su caso, se celebren.</li>
        <li>Administrar la línea de crédito, emitir facturas y realizar la cobranza extrajudicial y, en su caso, judicial.</li>
        <li>Prevenir y detectar fraudes, suplantación de identidad u otros ilícitos en perjuicio de usted o de Sistemas Contino.</li>
        <li>Cumplir las obligaciones legales, fiscales y de requerimientos de autoridades competentes.</li>
    </ul>
    <p class="mb-1"><strong>Finalidades secundarias (no necesarias para la relación).</strong></p>
    <ul class="ob-legal__list">
        <li>Enviarle información promocional sobre productos y servicios de Sistemas Contino.</li>
        <li>Realizar encuestas de calidad y estudios estadísticos o de mercado.</li>
    </ul>
    <p>Si no desea que sus datos se traten para estas finalidades secundarias, puede indicarlo marcando la casilla correspondiente en el Portal o enviando un correo a privacidad@sistemascontino.com.mx. Su negativa no será motivo para negarle el crédito ni los servicios que solicita.</p>

    <h4 class="ob-legal__h">5. Consulta a sociedades de información crediticia.</h4>
    <p>Para evaluar su solicitud, Sistemas Contino podrá consultar su historial crediticio en sociedades de información crediticia. Dicha consulta sólo se realizará si usted otorga la autorización expresa que se recaba en el Portal en un apartado específico, conforme a la Ley para Regular las Sociedades de Información Crediticia. Esa autorización es independiente de la aceptación de este aviso.</p>

    <h4 class="ob-legal__h">6. Mecanismo para otorgar su consentimiento.</h4>
    <p>Antes de capturar o cargar cualquier información, el Portal le mostrará el Aviso de Privacidad Simplificado y un vínculo a este aviso integral. Su consentimiento expreso se otorga marcando las casillas de aceptación y firmando electrónicamente la solicitud. Sistemas Contino conservará evidencia de la versión del aviso aceptada, la fecha y la hora.</p>

