    <p>En todos los casos, comunicaremos a los destinatarios el presente aviso y las finalidades a las que usted sujetó el tratamiento, y estos asumirán las mismas obligaciones que Sistemas Contino (art. 35 de la Ley).</p>

    <h4 class="ob-legal__h">9. Derechos ARCO.</h4>
    <p>Usted tiene derecho a acceder a sus datos personales y a conocer las condiciones de su tratamiento; a rectificarlos cuando sean inexactos o incompletos; a cancelarlos de nuestros archivos, registros y sistemas; y a oponerse a su tratamiento para fines específicos (derechos ARCO).</p>
    <p>Para ejercerlos, envíe su solicitud a privacidad@sistemascontino.com.mx o preséntela en nuestro domicilio. Conforme al artículo 28 de la Ley, deberá contener:</p>
    <ul class="ob-legal__list">
        <li>Su nombre y un domicilio o medio para recibir notificaciones.</li>
        <li>Los documentos que acrediten su identidad o, en su caso, la personalidad e identidad de su representante.</li>
        <li>La descripción clara y precisa de los datos respecto de los que busca ejercer el derecho (salvo en el derecho de acceso).</li>
        <li>El derecho que desea ejercer o lo que solicita.</li>
        <li>Cualquier otro elemento que facilite la localización de los datos. En rectificación, indique las modificaciones y adjunte la documentación que las sustente.</li>
    </ul>
    <p>Le comunicaremos nuestra determinación en un plazo máximo de 20 días hábiles a partir de la recepción de la solicitud y, si resulta procedente, la haremos efectiva dentro de los 15 días hábiles siguientes. Ambos plazos podrán ampliarse una sola vez por un periodo igual cuando se justifique. El ejercicio de estos derechos es gratuito; sólo podrán cobrarse los costos de reproducción o envío.</p>
    <p>Le informamos que no procederá la cancelación cuando los datos sean necesarios para el cumplimiento de un contrato vigente, deban conservarse por disposición legal o se ubique en otro supuesto del artículo 25 de la Ley.</p>

    <h4 class="ob-legal__h">10. Revocación del consentimiento.</h4>
    <p>Puede revocar en cualquier momento el consentimiento otorgado, sin efectos retroactivos, enviando su solicitud a privacidad@sistemascontino.com.mx con los requisitos señalados en la sección anterior. Le responderemos en un plazo máximo de 20 días hábiles. Tome en cuenta que, si la revocación se refiere a finalidades primarias, no será posible continuar con la evaluación de su solicitud o con la relación contractual.</p>

    <h4 class="ob-legal__h">11. Opciones para limitar el uso o divulgación de sus datos.</h4>
    <p>Puede solicitar que limitemos el uso o divulgación de sus datos enviando un correo a privacidad@sistemascontino.com.mx. Asimismo, puede inscribirse en el Registro Público para Evitar Publicidad de la Procuraduría Federal del Consumidor.</p>

    <h4 class="ob-legal__h">12. Conservación de los datos.</h4>
    <p>Sus datos se conservarán durante la vigencia de la relación contractual y por los plazos de prescripción legal o fiscal aplicables, tras los cuales serán bloqueados y suprimidos. Si su solicitud de crédito no es aprobada o usted desiste de ella, sus datos y documentos serán suprimidos en un plazo de 6 meses, salvo que deban conservarse por disposición legal. Los datos relativos al incumplimiento de obligaciones contractuales se eliminarán a los 72 meses contados desde el incumplimiento (art. 10 de la Ley).</p>

    <h4 class="ob-legal__h">13. Medidas de seguridad.</h4>
    <p>Sistemas Contino mantiene medidas de seguridad administrativas, técnicas y físicas para proteger sus datos contra daño, pérdida, alteración, destrucción o uso, acceso o tratamiento no autorizado, incluyendo el control de accesos al expediente de crédito. En caso de una vulneración de seguridad que afecte de forma significativa sus derechos patrimoniales o morales, se lo informaremos de inmediato.</p>

    <h4 class="ob-legal__h">14. Uso de cookies y tecnologías similares.</h4>
    <p>El Portal no utiliza cookies o tecnologías similares; en su caso, podrá deshabilitarlas desde la configuración de su navegador.</p>

    <h4 class="ob-legal__h">15. Cambios al aviso de privacidad.</h4>
    <p>Este aviso puede modificarse por cambios legales, de nuestras políticas internas o de los servicios que ofrecemos. Cualquier modificación se publicará en el Portal y en www.sistemascontino.com.mx, indicando la fecha de la última actualización. Si el cambio implica nuevas finalidades que requieran su consentimiento, se lo solicitaremos nuevamente.</p>

