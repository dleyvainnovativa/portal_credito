    <h4 class="ob-legal__h">2. ¿A quién aplica este aviso?</h4>
    <p>A las personas físicas que, por su propio derecho o en representación de una persona moral, solicitan a través del Portal el otorgamiento de una línea de crédito o el financiamiento de bienes y servicios de Sistemas Contino (en adelante, la &ldquo;Persona Titular&rdquo;).</p>

